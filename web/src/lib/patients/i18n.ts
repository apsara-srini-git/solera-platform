export type DictKey = keyof typeof es;
export type Dictionary = Dict;

export const DICT: Record<Lang, Dictionary> = { es, en };

export function dict(lang: Lang): Dictionary {
  return DICT[lang];
}

/** Replace {name} placeholders. */
export function fmt(s: string, vars: Record<string, string | number>): string {
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

/** One / other plural with a {n} placeholder. */
export function plural(n: number, one: string, other: string, lang: Lang): string {
  return fmt(n === 1 ? one : other, { n: n.toLocaleString(lang === "es" ? "es-ES" : "en-GB") });
}

export function locale(lang: Lang): string {
  return lang === "es" ? "es-ES" : "en-GB";
}

/** "5 de octubre de 2026" / "5 October 2026". Accepts yyyy-mm-dd or an ISO timestamp; Madrid time zone. */
export function formatDate(iso: string | null | undefined, lang: Lang): string {
  if (!iso) return DICT[lang].dateUnknown;
  const d = new Date(/^\d{4}-\d{2}-\d{2}$/.test(iso) ? `${iso}T12:00:00Z` : iso);
  if (Number.isNaN(d.getTime())) return iso;
  return new Intl.DateTimeFormat(locale(lang), { day: "numeric", month: "long", year: "numeric", timeZone: "Europe/Madrid" }).format(d);
}

export function formatNumber(n: number, lang: Lang): string {
  return n.toLocaleString(locale(lang));
}

/** Name of a language, in the UI language ("inglés" / "English"). */
export function langName(of: Lang, ui: Lang): string {
  return of === "es" ? DICT[ui].langNameEs : DICT[ui].langNameEn;
}

export function isLang(v: unknown): v is Lang {
  return v === "es" || v === "en";
}

