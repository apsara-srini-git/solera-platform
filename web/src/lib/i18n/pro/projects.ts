export const PROJECTS: Record<Lang, typeof en> = { en, es };

/**
 * Match reasons / flags are stored in English with each response (lib/questionnaire scoreResponse). Spanish display:
 * known patterns are translated here; anything unknown (or sponsor-typed requirement text) is shown as stored.
 */
export function matchLine(s: string, lang: Lang): string {
  if (lang === "en") return s;
  const eq = Object.entries(LABELS.en.equipment).find(([, v]) => s === `${v} not confirmed`);
  if (eq) return `${LABELS.es.equipment[eq[0]] ?? eq[1]}: sin confirmar`;
  const rules: [RegExp, (...m: string[]) => string][] = [
    [/^Site declined to participate$/, () => "El centro ha declinado participar"],
    [/^A key-criterion count exceeds the stated eligible patients per month \((.+)\)$/, (n) => `Algún criterio clave supera los pacientes elegibles al mes indicados (${n})`],
    [/^Commits (.+) of (.+) target patients \((\d+)%\)$/, (c, t, p) => `Se compromete a ${c} de ${t} pacientes objetivo (${p} %)`],
    [/^Commits (.+) patients \(no target set\)$/, (c) => `Se compromete a ${c} pacientes (sin objetivo fijado)`],
    [/^Commitment \((.+)\) exceeds stated eligible pool \((.+)\/month × (.+) months\)$/, (c, p, m) => `El compromiso (${c}) supera los pacientes elegibles indicados (${p}/mes × ${m} meses)`],
    [/^No enrolment commitment given$/, () => "Sin compromiso de inclusión"],
    [/^PI available$/, () => "IP disponible"],
    [/^No PI confirmed$/, () => "IP sin confirmar"],
    [/^(.+) trials in this condition already recruiting at the site$/, (n) => `${n} ensayos en esta indicación ya en reclutamiento en el centro`],
    [/^Contract start-up ~(.+) weeks$/, (w) => `Puesta en marcha del contrato: ~${w} semanas`],
    [/^IMP storage not confirmed$/, () => "Almacenamiento del medicamento en investigación sin confirmar"],
    [/^Not confirmed: (.+)$/, (x) => `Sin confirmar: ${x}`],
    [/^No dedicated phase I unit$/, () => "Sin unidad de fase I propia"],
    [/^No paediatric research unit$/, () => "Sin unidad de investigación pediátrica"],
    [/^Interest is tentative$/, () => "Interés provisional"],
  ];
  for (const [re, f] of rules) {
    const m = re.exec(s);
    if (m) return f(...m.slice(1));
  }
  return s;
}

/**
 * Project title in the UI language, rebuilt from the stored criteria (Project.name is saved once, in English, by
 * lib/questionnaire questionnaireSummaryLabel). Falls back to the stored name when the criteria can't be read.
 */
export function projectName(criteriaJson: string, storedName: string, lang: Lang): string {
  if (lang === "en") return storedName;
  try {
    const c = JSON.parse(criteriaJson) as { phase?: string; indication?: string; area?: string };
    if (!c.phase || !c.indication) return storedName;
    const L = LABELS[lang];
    const phase = (L.phases as Record<string, string>)[c.phase] ?? c.phase;
    const area = c.area ? ((L.areas as Record<string, string>)[c.area] ?? c.area) : "";
    return `${phase} · ${c.indication}${area ? ` · ${area}` : ""}`;
  } catch {
    return storedName;
  }
}
